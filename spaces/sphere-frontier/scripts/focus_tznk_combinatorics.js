function replaceFirstCombinatorics(set, variant) {
  const replacements = variants[variant];
  set.questions = [...replacements, ...set.questions.slice(replacements.length)];
  set.description =
    "Real-style TZNK with stronger combinatorics traps: OR/AND, roles vs teams, fixed members, excluded members, incompatible pairs, at least/exactly one, repeats.";
  set.updated_at = new Date().toISOString();
}

for (const file of findQuizBanks(repoRoot)) {
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  for (const variant of [1, 2, 3]) {
    const set = data.quiz_sets.find((item) => item.id === `exam-tznk-33-v${variant}`);
    if (!set) throw new Error(`Missing exam-tznk-33-v${variant}`);
    replaceFirstCombinatorics(set, variant);
  }
  data.updated_at = new Date().toISOString();
  fs.writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`, "utf8");
  console.log(`updated ${file}`);
}
