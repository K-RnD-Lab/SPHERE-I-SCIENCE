const repoRoot = path.resolve(__dirname, "../../..");

function findQuizBanks(root) {
  const out = [path.join(root, "spaces/sphere-frontier/app_data/quiz_bank_v1.json")];
  function walk(dir) {
    let entries = [];
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      const p = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(p);
      else if (
        entry.name === "quiz_bank_v1.json" &&
        p.includes("Master Prep Analytics") &&
        p.includes(`${path.sep}trainer${path.sep}app_data${path.sep}`)
      ) {
        out.push(p);
      }
    }
  }
  walk(root);
  return [...new Set(out)];
}

function choices(arr) {
  return { A: arr[0], B: arr[1], C: arr[2], D: arr[3] };
}

function q(id, variant, prompt, opts, correct, explanation, trap, life = "") {
  const choice_explanations = {};
  for (const [key, value] of Object.entries(opts)) {
    choice_explanations[key] =
      key === correct
        ? `✅ Так. ${explanation}`
        : `❌ Ні. "${value}" - пастка: ${trap}`;
  }
  return {
    id: `tznk-combo-focus-v${variant}-${String(id).padStart(2, "0")}`,
    subject: "all",
    sphere: "F",
    block: "logic",
    topic: "combinatorics",
    prompt,
    choices: opts,
    correct_answer: correct,
    explanation,
    variant,
    scientific_explanation:
      "🔬 Перед формулою треба розпізнати структуру умови: АБО чи І, одна група чи різні групи, чи є ролі, чи порядок важливий, чи хтось уже зафіксований, чи є заборонені варіанти.",
    real_life_example:
      life ||
      "🏠 Уяви, що збираєш людей у кімнату. Якщо люди просто сидять разом - порядок не важливий. Якщо один має бути головою, а інший заступником - це вже різні ролі.",
    choice_explanations,
  };
}

