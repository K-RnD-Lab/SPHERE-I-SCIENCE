function q(id, variant, block, topic, prompt, choices, correct, short, science, life, traps = {}) {
  const letters = Object.keys(choices);
  const choice_explanations = {};
  for (const letter of letters) {
    choice_explanations[letter] =
      letter === correct
        ? `✅ Так: ${short}`
        : traps[letter] || `❌ Пастка: звучить схоже, але тут ключова ознака інша. Правильна опора: ${choices[correct]}.`;
  }
  return {
    subject: "it",
    block,
    topic,
    prompt,
    choices,
    correct_answer: correct,
    explanation: short,
    variant,
    choice_explanations,
    scientific_explanation: science,
    real_life_example: life,
    id,
  };
}

